#!/usr/bin/env node
// The on-device Pi Durable bundle, from the SDK default-agent locks, with generated provenance.
// esbuild comes from ios/Runtime's own locked graph: `npm ci` there first.
import { builtinModules, createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const {build} = createRequire(path.join(root, 'ios/Runtime/package.json'))('esbuild');
const lock = JSON.parse(await readFile(path.join(root, 'default-agent/package-lock.json'), 'utf8'));
const expected = lock.packages['node_modules/@earendil-works/pi-durable'].version;
if (!/^\d+\.\d+\.\d+$/.test(expected)) throw new Error('A stable Pi SDK installation is required.');
const check = process.argv.includes('--check');
for (const name of ['pi-durable','pi-ai','chord','pi-schema','pi-telemetry']) {
  const manifest = JSON.parse(await readFile(path.join(root,`default-agent/node_modules/@earendil-works/${name}/package.json`),'utf8'));
  if (manifest.version !== expected) throw new Error(`Install default-agent's locked graph (npm ci): ${name} is ${manifest.version}, the lock has ${expected}`);
}
const output = path.join(root,'ios/Sources/PiDurableRuntime/Resources');
if (!check) await mkdir(output,{recursive:true});
// default-agent's modules are shared with the server's Pi Durable. Node built-ins they import
// only in code the bundle never reaches stay external; any that survives tree shaking fails the build.
const builtins = [...builtinModules, ...builtinModules.map(name => `node:${name}`)];
const result = await build({
  absWorkingDir:root,entryPoints:['ios/Runtime/entry.js'],bundle:true,platform:'browser',format:'iife',target:'es2022',minify:true,
  nodePaths:[path.join(root,'default-agent/node_modules')],outfile:path.join(output,'pi-durable.js'),write:false,
  external:builtins,legalComments:'linked',metafile:true,charset:'utf8',
  banner:{js:`// Generated by scripts/build-ios-pi-runtime.mjs. Pi Durable ${expected}; do not edit.`},
});
const reached = Object.values(result.metafile.outputs).flatMap(file => file.imports).filter(item => item.external).map(item => item.path);
if (reached.length) throw new Error(`The bundle reaches Node built-ins: ${[...new Set(reached)].join(', ')}`);
const packageOf = input => {
  const rest = input.split('node_modules/').at(-1).split('/');
  return rest.slice(0, rest[0].startsWith('@') ? 2 : 1).join('/');
};
// What tree shaking kept, not everything esbuild read.
const kept = Object.values(result.metafile.outputs).flatMap(file => Object.entries(file.inputs)).filter(([, input]) => input.bytesInOutput > 0).map(([file]) => file);
const packages = [...new Set(kept.filter(p=>p.includes('node_modules/')).map(packageOf))].sort();
const provenance = JSON.stringify({sdkVersion:expected,entry:'ios/Runtime/entry.js',packages},null,2)+'\n';
// The reviewed notices (the Pi packages ship none of their own), headed with the bundled release.
const notices = (await readFile(path.join(output, 'THIRD_PARTY_LICENSES.txt'), 'utf8'))
  .replace(/^Pi Durable, Pi AI, Pi Schema, Chord and Pi Telemetry [^\n]+\nhttps:\/\/github\.com\/earendil-works\/pi\/tree\/v[^\n]+/,
    `Pi Durable, Pi AI, Pi Schema, Chord and Pi Telemetry ${expected}\nhttps://github.com/earendil-works/pi/tree/v${expected}`);
const files = [...result.outputFiles.map(file=>({path:file.path,content:file.text})),
  {path:path.join(output,'provenance.json'),content:provenance},
  {path:path.join(output,'THIRD_PARTY_LICENSES.txt'),content:notices},
  {path:path.join(root,'ios/Sources/MobileInference/PiSDKVersion.swift'),content:`// Generated by scripts/build-ios-pi-runtime.mjs; do not edit.\nenum PiSDKVersion { static let value = "${expected}" }\n`},
];
for (const file of files) {
  if (check) {
    const current = await readFile(file.path,'utf8');
    if (current !== file.content) throw new Error(`Stale runtime resource: ${path.relative(root,file.path)}. Run node scripts/build-ios-pi-runtime.mjs`);
  } else await writeFile(file.path,file.content);
}
console.log(`${check?'Verified':'Bundled'} Pi Durable ${expected}: ${packages.join(', ')}`);
