#!/usr/bin/env node
// Reproducible browser bundle from the same locked SDK used by the desktop runtime.
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'default-agent/package.json'));
const {build} = require('esbuild');
const lock = JSON.parse(await readFile(path.join(root, 'default-agent/package-lock.json'), 'utf8'));
const expected = lock.packages['node_modules/@earendil-works/pi-durable'].version;
if (!/^1\.\d+\.\d+$/.test(expected)) throw new Error('Review the supported Pi SDK major before bundling.');
const check = process.argv.includes('--check');
for (const name of ['pi-durable','pi-ai','chord']) {
  const manifest = JSON.parse(await readFile(path.join(root,`default-agent/node_modules/@earendil-works/${name}/package.json`),'utf8'));
  if (manifest.version !== expected) throw new Error(`Review SDK update before bundling ${name}@${manifest.version}; expected ${expected}`);
}
const output = path.join(root,'ios/Sources/PiDurableRuntime/Resources');
if (!check) await mkdir(output,{recursive:true});
const result = await build({
  absWorkingDir:root,entryPoints:['ios/Runtime/entry.js'],bundle:true,platform:'browser',format:'iife',target:'es2022',minify:true,
  nodePaths:[path.join(root,'default-agent/node_modules')],outfile:path.join(output,'pi-durable.js'),write:false,
  legalComments:'linked',metafile:true,charset:'utf8',
  banner:{js:`// Generated by scripts/build-ios-pi-runtime.mjs. Pi Durable ${expected}; do not edit.`},
});
const packages = [...new Set(Object.keys(result.metafile.inputs).filter(p=>p.includes('node_modules/')).map(p=>p.split('node_modules/').at(-1).split('/').slice(0,p.split('node_modules/').at(-1).startsWith('@')?2:1).join('/')))].sort();
const provenance = JSON.stringify({sdkVersion:expected,entry:'ios/Runtime/entry.js',packages},null,2)+'\n';
// Keep reviewed copyright notices, including TypeBox, rather than dropping them
// when a package release omits its standalone license file.
const notices = (await readFile(path.join(output, 'THIRD_PARTY_LICENSES.txt'), 'utf8'))
  .replace(/^Pi Durable, Pi AI and Chord [^\n]+\nhttps:\/\/github\.com\/earendil-works\/pi\/tree\/v[^\n]+/,
    `Pi Durable, Pi AI and Chord ${expected}\nhttps://github.com/earendil-works/pi/tree/v${expected}`);
const files = [...result.outputFiles.map(file=>({path:file.path,content:file.text})),
  {path:path.join(output,'provenance.json'),content:provenance},
  {path:path.join(output,'THIRD_PARTY_LICENSES.txt'),content:notices},
  {path:path.join(root,'ios/Sources/CompanionInference/PiSDKVersion.swift'),content:`// Generated by scripts/build-ios-pi-runtime.mjs; do not edit.\nenum PiSDKVersion { static let value = "${expected}" }\n`},
];
for (const file of files) {
  if (check) {
    const current = await readFile(file.path,'utf8');
    if (current !== file.content) throw new Error(`Stale runtime resource: ${path.relative(root,file.path)}. Run node scripts/build-ios-pi-runtime.mjs`);
  } else await writeFile(file.path,file.content);
}
console.log(`${check?'Verified':'Bundled'} Pi Durable ${expected}: ${packages.join(', ')}`);
